"""Tests for HuntResultSchema — dynamic hunt output column generation."""

import pytest

from dfe_engine.hunts.hunt_output import (
    HuntResultSchema,
)


class TestHuntResultSchemaInit:
    """Test HuntResultSchema initialization from profile."""

    def test_loads_timeseries_profile(self):
        """Default profile should be timeseries."""
        schema = HuntResultSchema()
        assert schema.profile_name == "timeseries"

    def test_loads_minimal_profile(self):
        """Minimal profile should load without error."""
        schema = HuntResultSchema(profile_name="minimal")
        assert schema.profile_name == "minimal"

    def test_loads_passthrough_profile(self):
        """Passthrough profile should load without error."""
        schema = HuntResultSchema(profile_name="passthrough")
        assert schema.profile_name == "passthrough"

    def test_invalid_profile_raises(self):
        """Non-existent profile should raise."""
        with pytest.raises(Exception):
            HuntResultSchema(profile_name="nonexistent")

    def test_detection_columns_defined(self):
        """Detection columns should include matched_uuid, rule_id, etc."""
        schema = HuntResultSchema()
        names = [dc.name for dc in schema.detection_columns]
        assert "matched_uuid" in names
        assert "rule_id" in names
        assert "rule_name" in names
        assert "source_table" in names
        assert "hunt_name" in names
        assert "severity" in names


