class TestSelectExpression:
    """Test SELECT expression generation."""

    def test_produces_valid_expression(self):
        """Select expression should be non-empty string."""
        schema = HuntResultSchema()
        expr = schema.select_expression(
            rule_id="test_rule_01",
            rule_name="Test Rule",
            source_table="windows_audit",
            hunt_name="test_hunt",
            severity="high",
        )
        assert isinstance(expr, str)
        assert len(expr) > 0

    def test_includes_matched_uuid_alias(self):
        """Should alias _uuid AS matched_uuid."""
        schema = HuntResultSchema()
        expr = schema.select_expression(
            rule_id="r1",
            rule_name="Rule 1",
            source_table="src",
            hunt_name="hunt",
            severity="low",
        )
        assert "_uuid AS matched_uuid" in expr

    def test_includes_literal_values(self):
        """Rule metadata should appear as string literals."""
        schema = HuntResultSchema()
        expr = schema.select_expression(
            rule_id="win_priv_esc_01",
            rule_name="Windows Priv Esc",
            source_table="windows_audit",
            hunt_name="win_hunt",
            severity="critical",
        )
        assert "'win_priv_esc_01' AS rule_id" in expr
        assert "'Windows Priv Esc' AS rule_name" in expr
        assert "'critical' AS severity" in expr

    def test_includes_json_column(self):
        """Timeseries profile should include _json in SELECT."""
        schema = HuntResultSchema()
        expr = schema.select_expression(
            rule_id="r",
            rule_name="r",
            source_table="s",
            hunt_name="h",
            severity="low",
        )
        assert "_json" in expr

    def test_escapes_single_quotes(self):
        """Values with single quotes should be escaped."""
        schema = HuntResultSchema()
        expr = schema.select_expression(
            rule_id="it's_a_rule",
            rule_name="Rule",
            source_table="src",
            hunt_name="hunt",
            severity="low",
        )
        assert "'it''s_a_rule' AS rule_id" in expr

    def test_escapes_backslashes_before_quotes(self):
        """A trailing backslash must not escape the literal's closing quote."""
        schema = HuntResultSchema()
        expr = schema.select_expression(
            rule_id="r1",
            rule_name="Analyst's share C:\\Temp\\",
            source_table="src",
            hunt_name="hunt",
            severity="low",
        )
        assert "'Analyst''s share C:\\\\Temp\\\\' AS rule_name" in expr


class TestBuildInsertSelect:
    """Test full INSERT INTO ... SELECT generation."""

    def test_produces_complete_sql(self):
        """Should produce a valid INSERT INTO ... SELECT ... FROM ... WHERE."""
        schema = HuntResultSchema()
        sql = schema.build_insert_select(
            target_db="acme",
            target_table="detection",
            source_db="acme",
            source_table="windows_audit",
            where_clause="process_executable IN ('certutil.exe')",
            rule_id="win_cert_abuse",
            rule_name="Certificate Abuse",
            hunt_name="windows_detection",
            severity="high",
        )
        assert "INSERT INTO `acme`.`detection`" in sql
        assert "FROM `acme`.`windows_audit`" in sql
        assert "{timestamp_condition}" in sql
        assert "process_executable IN ('certutil.exe')" in sql

    def test_insert_columns_match_select(self):
        """Number of insert columns should match select expressions."""
        schema = HuntResultSchema()
        sql = schema.build_insert_select(
            target_db="org",
            target_table="results",
            source_db="org",
            source_table="src",
            where_clause="x = 1",
            rule_id="r1",
            rule_name="Rule",
            hunt_name="hunt",
            severity="low",
        )
        # Extract insert column count from the parenthesized list
        insert_line = next(line for line in sql.split("\n") if line.strip().startswith("("))
        insert_count = insert_line.count(",") + 1
        # Extract select expression count (lines between SELECT and FROM)
        select_lines = []
        in_select = False
        for line in sql.split("\n"):
            if "SELECT" in line:
                in_select = True
                continue
            if "FROM" in line:
                break
            if in_select:
                select_lines.append(line.strip())
        select_expr = " ".join(select_lines)
        # Count top-level commas in select (not inside quotes)
        select_count = select_expr.count(",") + 1
        assert insert_count == select_count

    def test_empty_where_clause(self):
        """Empty WHERE clause should only have timestamp condition."""
        schema = HuntResultSchema()
        sql = schema.build_insert_select(
            target_db="org",
            target_table="results",
            source_db="org",
            source_table="src",
            where_clause="",
            rule_id="r1",
            rule_name="Rule",
            hunt_name="hunt",
            severity="low",
        )
        assert "WHERE {timestamp_condition}" in sql
        # Should not have trailing AND
        assert (
            "AND" not in sql.split("WHERE")[1].strip()
            or sql.split("WHERE")[1].strip() == "{timestamp_condition}"
        )

    def test_custom_timestamp_placeholder(self):
        """Should support custom timestamp placeholder."""
        schema = HuntResultSchema()
        sql = schema.build_insert_select(
            target_db="org",
            target_table="results",
            source_db="org",
            source_table="src",
            where_clause="x = 1",
            rule_id="r1",
            rule_name="Rule",
            hunt_name="hunt",
            severity="low",
            timestamp_placeholder="{{ts_cond}}",
        )
        assert "{{ts_cond}}" in sql


